#!/usr/bin/env bash
# Разворачивает окружение агентов.
#
#   1) создаёт пустые рабочие папки (гит не хранит пустые папки сам);
#   2) предлагает поставить навык «Сборщик агентов» глобально — тогда его можно
#      звать из любого проекта, а не только из этой папки.
#
# Ничего не удаляет и ничего не отправляет наружу.
#
#   bash install.sh              спросит про глобальную установку
#   bash install.sh --global     сразу ставить глобально
#   bash install.sh --no-global  только папки

set -euo pipefail
cd "$(dirname "$0")"

зел() { printf '\033[32m%s\033[0m\n' "$1"; }
жёл() { printf '\033[33m%s\033[0m\n' "$1"; }
сер() { printf '%s\n' "$1"; }

echo
printf '\033[36m%s\033[0m\n' '  Окружение агентов — установка'
echo

# ── 1. Рабочие папки ─────────────────────────────────────────────────────────
for п in проекты входящие результаты корзина окружение; do
  if [ -d "$п" ]; then
    сер "  папка уже есть:  $п"
  else
    mkdir -p "$п"
    зел "  создал папку:    $п"
  fi
done

# ── 2. Навык глобально ───────────────────────────────────────────────────────
ставить=""
case "${1:-}" in
  --global)    ставить="да" ;;
  --no-global) ставить="нет" ;;
  *)
    echo
    жёл '  Поставить «Сборщика агентов» глобально?'
    сер '  Тогда его можно звать из любой папки, а не только из этой.'
    printf '  Ставить? (д/н): '
    read -r ответ || ответ="н"
    case "$ответ" in [дДyY]*) ставить="да" ;; *) ставить="нет" ;; esac
    ;;
esac

if [ "$ставить" = "да" ]; then
  поставить() {
    откуда="$1"; куда="$2"; имя="$3"
    [ -d "$откуда" ] || return 0
    mkdir -p "$(dirname "$куда")"
    if [ -e "$куда" ]; then
      # не затираем молча: старую копию отодвигаем с датой в имени
      запас="$куда.старый-$(date +%Y-%m-%d-%H%M)"
      mv "$куда" "$запас"
      жёл "  прежний навык отложен: $запас"
    fi
    cp -R "$откуда" "$куда"
    зел "  навык поставлен для $имя: $куда"
  }
  поставить ".claude/skills/sborshchik" "$HOME/.claude/skills/sborshchik" "Claude Code"
  поставить ".codex/skills/sborshchik"  "$HOME/.codex/skills/sborshchik"  "Codex"
else
  сер '  Глобально не ставлю — навык работает, когда запускаешь агента из этой папки.'
fi

# ── 3. Что дальше ────────────────────────────────────────────────────────────
echo
зел '  Готово.'
echo
сер '  Дальше:'
сер '    1. Запусти в этой папке:  claude'
сер '    2. Скажи своими словами:  собери мне агента, который …'
сер '       (или вызови навык явно: /sborshchik)'
echo
сер '  Общий дашборд — файл Дашборд.html, открывается двойным кликом.'
echo
